"""
Generate ``shared/test-vectors/face-pipeline.json``: golden values that the TypeScript (web) and
Dart (Flutter) implementations are unit tested against, so all clients produce compatible
embeddings.

    cd backend/frs && python tools/generate_test_vectors.py
"""
import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'src'))

from face_pipeline.alignment import alignment_matrix  # noqa: E402
from face_pipeline.embedding import l2_normalize, cosine_similarity, fuse_embeddings, encode_base64  # noqa: E402
from face_pipeline.pose import HeadPose, pose_from_landmarks_3d, classify_pose  # noqa: E402
from face_pipeline.preprocess import to_model_input  # noqa: E402

OUTPUT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', 'shared', 'test-vectors',
                                      'face-pipeline.json'))

# canonical 3D head points (pixels, x right, y down, z away from camera) for a frontal face
CANONICAL_HEAD = {
    "left_eye": [-32.0, -10.0, 8.0],
    "right_eye": [32.0, -10.0, 8.0],
    "forehead": [0.0, -70.0, 6.0],
    "chin": [0.0, 75.0, 6.0],
}


def rotation(yaw: float, pitch: float, roll: float) -> np.ndarray:
    """Rotation producing the given pose in the shared convention (see face_pipeline.pose)."""
    y, p, r = (math.radians(v) for v in (yaw, pitch, roll))
    ry = np.array([[math.cos(y), 0, -math.sin(y)], [0, 1, 0], [math.sin(y), 0, math.cos(y)]])
    rx = np.array([[1, 0, 0], [0, math.cos(p), math.sin(p)], [0, -math.sin(p), math.cos(p)]])
    rz = np.array([[math.cos(r), math.sin(r), 0], [-math.sin(r), math.cos(r), 0], [0, 0, 1]])
    return rz @ ry @ rx


def r(values, digits=6):
    return [round(float(v), digits) for v in values]


def build() -> dict:
    rng = np.random.default_rng(42)

    alignment = []
    frontal = np.array([[250.0, 230.0], [350.0, 228.0], [300.0, 290.0], [262.0, 345.0], [338.0, 343.0]])
    for i in range(6):
        angle = math.radians(rng.uniform(-25, 25))
        scale = rng.uniform(0.4, 2.5)
        rot = np.array([[math.cos(angle), -math.sin(angle)], [math.sin(angle), math.cos(angle)]])
        pts = (frontal - frontal.mean(0)) @ rot.T * scale + rng.uniform(100, 500, size=2)
        pts += rng.normal(0, 2.0, size=pts.shape)  # detector noise
        alignment.append({"landmarks": [r(p, 4) for p in pts],
                          "matrix": [r(row) for row in alignment_matrix(np.round(pts, 4))]})
    four = np.round(np.vstack([frontal[:3], frontal[3:].mean(0)]), 4)
    alignment.append({"landmarks": [r(p, 4) for p in four], "matrix": [r(row) for row in alignment_matrix(four)]})

    pose = []
    for yaw, pitch, roll in [(0, 0, 0), (25, 0, 0), (-25, 0, 0), (0, 20, 0), (0, -20, 0), (0, 0, 15),
                             (18, -12, 6), (-30, 8, -10)]:
        rot = rotation(yaw, pitch, roll)
        pts = {k: (rot @ np.array(v)) + np.array([320.0, 240.0, 0.0]) for k, v in CANONICAL_HEAD.items()}
        est = pose_from_landmarks_3d(pts["left_eye"], pts["right_eye"], pts["forehead"], pts["chin"])
        pose.append({"points": {k: r(v, 4) for k, v in pts.items()},
                     "pose": {"yaw": round(est.yaw, 4), "pitch": round(est.pitch, 4), "roll": round(est.roll, 4)},
                     "label": classify_pose(est)})

    classify = []
    for yaw, pitch, roll in [(0, 0, 0), (9, -9, 9), (20, 0, 0), (-20, 0, 0), (0, 20, 0), (0, -20, 0), (50, 0, 0),
                             (0, 0, 30), (12, 12, 0)]:
        classify.append({"pose": {"yaw": yaw, "pitch": pitch, "roll": roll},
                         "label": classify_pose(HeadPose(yaw, pitch, roll))})

    rgb = np.array([[[0, 127, 255], [10, 20, 30]], [[255, 255, 255], [128, 64, 32]]], dtype=np.uint8)
    preprocess = {"width": 2, "height": 2, "rgb": rgb.reshape(-1).tolist(),
                  "tensor": r(to_model_input(rgb).reshape(-1), 7)}

    a = rng.normal(size=8)
    b = rng.normal(size=8)
    c = rng.normal(size=8)
    embedding = {
        "a": r(a), "b": r(b), "c": r(c),
        "a_normalized": r(l2_normalize(np.round(a, 6))),
        "cosine_ab": round(cosine_similarity(np.round(a, 6), np.round(b, 6)), 6),
        "fused_abc": r(fuse_embeddings([np.round(a, 6), np.round(b, 6), np.round(c, 6)])),
        "base64_of_1_2_3": encode_base64([1.0, -2.0, 3.5]),
    }

    return {
        "description": "Golden values for the client side face pipeline. Generated by "
                       "backend/frs/tools/generate_test_vectors.py - do not edit by hand.",
        "alignment": alignment,
        "pose": pose,
        "classify": classify,
        "preprocess": preprocess,
        "embedding": embedding,
    }


def main():
    data = build()
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, 'w') as f:
        json.dump(data, f, indent=1)
        f.write('\n')
    print(f'written {OUTPUT}')


if __name__ == '__main__':
    main()
